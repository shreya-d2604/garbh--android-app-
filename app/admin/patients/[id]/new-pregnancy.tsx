import { zodResolver } from '@hookform/resolvers/zod';
import { Stack, useLocalSearchParams, useRouter } from 'expo-router';
import { useMemo, useState } from 'react';
import { useForm } from 'react-hook-form';
import { useTranslation } from 'react-i18next';

import { Button, DateField, InfoBanner, Screen } from '@/components';
import { addDays, todayISO } from '@/domain/pregnancy-math';
import { firstParam } from '@/features/admin/components/ui';
import { adminErrorKey } from '@/features/admin/errors';
import { useCreatePregnancy } from '@/features/admin/hooks';
import { newPregnancySchema } from '@/features/admin/schemas';

/** Start a new (active) pregnancy for a patient. The 12-visit plan is generated by the database. */
export default function NewPregnancy() {
  const { t } = useTranslation('admin');
  const router = useRouter();
  const id = firstParam(useLocalSearchParams<{ id: string }>().id);
  const today = todayISO();
  const schema = useMemo(() => newPregnancySchema(today), [today]);
  const create = useCreatePregnancy();
  const [error, setError] = useState<string | null>(null);
  const { control, handleSubmit, formState } = useForm<{ lmp_date: string }>({
    resolver: zodResolver(schema),
    defaultValues: { lmp_date: '' },
  });

  const onSubmit = handleSubmit(async ({ lmp_date }) => {
    setError(null);
    try {
      await create.mutateAsync({ patientId: id, lmp: lmp_date });
      router.back();
    } catch (e) {
      setError(adminErrorKey(e as Error));
    }
  });

  return (
    <Screen edges={['bottom']}>
      <Stack.Screen options={{ title: t('pregnancy.add') }} />
      {error ? <InfoBanner tone="danger" message={t(error)} /> : null}
      <DateField
        control={control}
        name="lmp_date"
        label={t('pregnancy.lmp')}
        minimumDate={addDays(today, -300)}
        maximumDate={today}
      />
      <Button label={t('pregnancy.create')} onPress={() => void onSubmit()} loading={formState.isSubmitting} />
    </Screen>
  );
}
